def normalize_institution(name: str) -> str:
    """机构名标准化：别名 → 标准名；未收录的去除证券后缀类噪音"""
    if not name:
        return ""
    name = name.strip()
    # 1) 精确/包含匹配别名
    for alias, std in ALIASES.items():
        if name == alias or name.startswith(alias):
            return std
    # 2) 常见后缀归一：XX证券 / XX证券股份有限公司
    m = re.match(r'^(.{2,8}?)(证券|证券股份)(?:有限公司)?$', name)
    if m:
        base = m.group(1)
        return ALIASES.get(base, f"{base}证券")
    return name
